import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import path from 'node:path';
const monsterData=JSON.parse(readFileSync(new URL('../data/monsters.json',import.meta.url),'utf8'));
const ptNames=JSON.parse(readFileSync(new URL('../data/nomes-pt-BR.json',import.meta.url),'utf8'));
test('SRD com 322 fichas carregado, busca e combate funcionam',async()=>{
 const nodes=new Map(),events={};
 class Node{constructor(){this.innerHTML='';this.textContent='';this.classList={toggle(){}};this.dataset={};}appendChild(){}remove(){}}
 globalThis.document={getElementById(id){if(!nodes.has(id))nodes.set(id,new Node());return nodes.get(id)},querySelectorAll(){return[]},addEventListener(name,fn){events[name]=fn},createElement(){return new Node()}};
 const db=new Map();
 globalThis.localStorage={getItem:k=>db.get(k)??null,setItem:(k,v)=>db.set(k,v),removeItem:k=>db.delete(k)};
 globalThis.window={scrollTo(){}};
 Object.defineProperty(globalThis,'navigator',{configurable:true,value:{}});
 globalThis.confirm=()=>true;
 globalThis.prompt=()=>null;
 const oldInterval=globalThis.setInterval;
 globalThis.setInterval=()=>0;
 const fetched=[];
 globalThis.fetch=async(url)=>{fetched.push(String(url));if(String(url).includes('nomes-pt-BR.json'))return{ok:true,json:async()=>ptNames};return{ok:true,json:async()=>monsterData}};
 try{
  await import('../app.js');
  await new Promise(resolve=>setTimeout(resolve,30));
  const get=id=>document.getElementById(id).innerHTML;
  assert.equal(monsterData.monsters.length,322);
  assert.match(get('view'),/322/);
  assert.match(get('view'),/atlas-hero/);
  assert.match(get('view'),/Comece de onde parou/);
  assert.equal((get('view').match(/class="atlas-stat /g)||[]).length,4);
  const layout=readFileSync(new URL('../index.html',import.meta.url),'utf8');
  assert.match(layout,/atlas-v3.css/);
  assert.match(layout,/ux-responsive-v1.css/);
  assert.ok(!fetched.some(u=>u.includes('monsters.pt-BR.json')));
  assert.match(layout,/globalSearchForm/);
  assert.match(layout,/atlas-logo.svg/);
  assert.match(readFileSync(new URL('../atlas-v3.css',import.meta.url),'utf8'),/atlas-stats/);
  assert.match(readFileSync(new URL('../assets/hero-citadel.svg',import.meta.url),'utf8'),/<svg/);
  const click=async(kind, value,id,extra={})=>events.click({target:{closest(sel){if(kind==='view'&&sel==='[data-view]')return{dataset:{view:value}};if(kind==='action'&&sel==='[data-action]')return{dataset:{action:value,id,...extra}};return null},matches(){return false}}});
  await click('view','bestiary');
  assert.match(get('view'),/Bestiário/);
  assert.ok(Object.keys(ptNames).length>=322);
  await click('action','details','srd:goblin');
  assert.match(get('modalRoot'),/sheet-layout/);
  assert.match(get('modalRoot'),/creature-portrait/);
  await click('action','close');
  await click('action','add-encounter','srd:goblin');
  await click('view','builder');
  assert.match(get('view'),/Goblin/);
  assert.match(get('view'),/encounter-command/);
  assert.match(get('view'),/encounter-summary/);
  assert.match(layout,/tactical-v2.css/);
  await click('action','start-combat');
  assert.match(get('view'),/Mesa de combate/);
  assert.match(get('view'),/MAPA TÁTICO/);
  assert.match(get('view'),/Dano em área/);
  assert.match(get('view'),/Goblin/);
  let stateBefore=JSON.parse(db.get('central-mestre-state-v2'));
  const firstId=stateBefore.combat.list[0].id;
  await click('action','focus-combat',firstId);
  assert.match(get('view'),/Dano rápido/);
  assert.match(get('view'),/Cura rápida/);
  assert.match(get('view'),/tactical-sheet-body/);
  const originalHP=stateBefore.combat.list[0].hp;
  await click('action','quick-hp',null,{amount:'-5'});
  let stateAfter=JSON.parse(db.get('central-mestre-state-v2'));
  assert.equal(stateAfter.combat.list[0].hp,originalHP-5);
  await click('action','undo-hp');
  stateAfter=JSON.parse(db.get('central-mestre-state-v2'));
  assert.equal(stateAfter.combat.list[0].hp,originalHP);
  let beforeAdd=JSON.parse(db.get('central-mestre-state-v2'));
  const activeBeforeAdd=beforeAdd.combat.list[beforeAdd.combat.turn].id;
  await click('action','add-combat','srd:goblin');
  let afterAdd=JSON.parse(db.get('central-mestre-state-v2'));
  assert.equal(afterAdd.combat.list[afterAdd.combat.turn].id,activeBeforeAdd);
  const firstTwo=afterAdd.combat.list.slice(0,2).map(f=>f.id);
  await click('action','toggle-combat-sheet',firstTwo[0]);
  await click('action','toggle-combat-sheet',firstTwo[1]);
  assert.ok((get('view').match(/class="tactical-fighter is-open/g)||[]).length>=2);
  assert.doesNotMatch(get('view'),/Condição em grupo/);
  assert.doesNotMatch(get('view'),/conditions-grid/);
  await click('action','toggle-batch-target',firstTwo[0]);
  await click('action','toggle-batch-target',firstTwo[1]);
  document.getElementById('batchAmount').value='4';
  const beforeBatch=JSON.parse(db.get('central-mestre-state-v2')).combat.list.slice(0,2).map(f=>f.hp);
  await click('action','batch-damage');
  const afterBatchState=JSON.parse(db.get('central-mestre-state-v2'));
  assert.equal(afterBatchState.combat.list.find(f=>f.id===firstTwo[0]).hp,Math.max(0,beforeBatch[0]-4));
  assert.equal(afterBatchState.combat.list.find(f=>f.id===firstTwo[1]).hp,Math.max(0,beforeBatch[1]-4));
  await click('action','batch-open-selected');
  assert.ok((get('view').match(/class="tactical-fighter is-open/g)||[]).length>=2);
  await click('action','undo-batch-hp');
  const restored=JSON.parse(db.get('central-mestre-state-v2'));
  assert.equal(restored.combat.list.find(f=>f.id===firstTwo[0]).hp,beforeBatch[0]);
  await click('action','next-turn');
  assert.match(get('view'),/RODADA/);
  beforeAdd=JSON.parse(db.get('central-mestre-state-v2'));
  const activeBeforeMerge=beforeAdd.combat.list[beforeAdd.combat.turn].id;
  const roundBeforeMerge=beforeAdd.combat.round;
  await click('action','start-combat');
  afterAdd=JSON.parse(db.get('central-mestre-state-v2'));
  assert.equal(afterAdd.combat.list[afterAdd.combat.turn].id,activeBeforeMerge);
  assert.equal(afterAdd.combat.round,roundBeforeMerge);
  assert.ok(db.has('central-mestre-state-v2'));
  const redesignedCSS=readFileSync(new URL('../theme-v2.css',import.meta.url),'utf8');
  assert.match(redesignedCSS,/sheet-layout/);
  assert.match(redesignedCSS,/hp-console/);
  assert.match(redesignedCSS,/data-section="combat"/);
 }finally{globalThis.setInterval=oldInterval}
});
